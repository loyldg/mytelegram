using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MyTelegram.SourceGenerators;

[Generator]
public sealed class MyTelegramDomainObjectsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methodModels = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => IsCandidateMethod(node),
                static (ctx, _) => TransformMethod(ctx)
            )
            .Where(static m => m is not null);

        context.RegisterSourceOutput(methodModels,
            static (spc, model) => { Generate_Event_Command_CommandHandler(spc, model!); });
    }

    private static string BuildCtorParams(IEnumerable<ParameterModel> parameters)
    {
        return string.Join(",\n",
            parameters.Select(p =>
                $"        {p.ParameterType} {(string.IsNullOrEmpty(p.DefaultValue) ? p.ParameterName : $"{p.ParameterName} = {p.DefaultValue}")}"));
    }

    private static string BuildMethodArguments(IEnumerable<ParameterModel> parameters)
    {
        return string.Join(", ", parameters.Select(p => $"command.{Capitalize(p.ParameterName)}"));
    }

    private static string BuildProperties(IEnumerable<ParameterModel> parameters, bool hasRequestInfo, bool doNotInheritRequestCommand2 = false)
    {
        var sb = new StringBuilder();
        foreach (var p in parameters)
        {
            if (hasRequestInfo && p.ParameterName == "requestInfo" && !doNotInheritRequestCommand2)
            {
                continue;
            }

            sb.AppendLine(
                $"        public {p.ParameterType} {Capitalize(p.ParameterName)} {{ get; }} = {p.ParameterName};");
        }

        return sb.ToString();
    }

    private static string Capitalize(string s)
    {
        return char.ToUpper(s[0]) + s[1..];
    }

    private static void Generate_Event_Command_CommandHandler(SourceProductionContext ctx, MethodInfoModel model)
    {
        var methodSyntax = model.MethodSyntax;
        var methodSymbol = model.MethodSymbol;

        var methodName = methodSyntax.Identifier.Text;
        var parameters = model.EventParameters; // methodSyntax.ParameterList.Parameters;

        var hasRequestInfo =
            parameters.Count > 0 &&
            parameters[0].ParameterType.EndsWith("RequestInfo");

        var commandParameters = model.CommandParameters; // methodSyntax.ParameterList.Parameters;

        var eventName = model.EventName;
        var commandName = GetCommandName(model.AggregateName, methodName, methodSymbol);
        var handlerName = commandName + "Handler";

        var eventCtorParameters = parameters?.Count > 0 ? BuildCtorParams(parameters) : string.Empty;
        var commandCtorParameters = BuildCtorParams(commandParameters);

        var eventProperties = BuildProperties(parameters, hasRequestInfo);
        var commandProperties = BuildProperties(commandParameters, hasRequestInfo, model.DoNotInheritRequestCommand);
        var methodArgs = BuildMethodArguments(commandParameters);

        var eventBase = hasRequestInfo
            ? $"RequestAggregateEvent2<{model.AggregateName}, {model.IdType}>({parameters[0].ParameterName})"
            : $"AggregateEvent<{model.AggregateName}, {model.IdType}>";

        var commandBase = hasRequestInfo && !model.DoNotInheritRequestCommand
            ? $"RequestCommand2<{model.AggregateName}, {model.IdType}, IExecutionResult>(aggregateId, {parameters[0].ParameterName})"
            : $"Command<{model.AggregateName}, {model.IdType}, IExecutionResult>(aggregateId)";

        //Debug.WriteLine($"AggregateName:{model.AggregateName},idType:{model.IdType}");

        // Event
        var eventSource = $$"""
                            // <auto-generated />
                            #nullable enable
                            using EventFlow.Aggregates;
                            using EventFlow.Aggregates.ExecutionResults;

                            namespace {{model.Namespace}};

                            public partial class {{eventName}}(
                            {{eventCtorParameters}}
                            ) : {{eventBase}}
                            {
                            {{eventProperties}}
                            }
                            """;

        ctx.AddSource($"{model.AggregateName}_{eventName}.g.cs", eventSource);

        // Command
        var commandSource = $$"""
                              // <auto-generated />
                              #nullable enable
                              using EventFlow.Commands;
                              using EventFlow.Aggregates.ExecutionResults;

                              namespace {{model.Namespace}};

                              public partial class {{commandName}}(
                                  {{model.IdType}} aggregateId
                              {{(string.IsNullOrEmpty(commandCtorParameters) ? "" : $",{commandCtorParameters}")}}
                              ) : {{commandBase}}
                              {
                              {{commandProperties}}
                              }
                              """;

        ctx.AddSource($"{model.AggregateName}_{commandName}.g.cs", commandSource);

        // Handler
        var handlerSource = $$"""
                              // <auto-generated />
                              #nullable enable
                              using EventFlow.Commands;
                              using System.Threading;
                              using System.Threading.Tasks;

                              namespace {{model.Namespace}};

                              public class {{handlerName}}
                                  : CommandHandler<{{model.AggregateName}}, {{model.IdType}}, {{commandName}}>
                              {
                                  public override Task ExecuteAsync(
                                      {{model.AggregateName}} aggregate,
                                      {{commandName}} command,
                                      CancellationToken cancellationToken)
                                  {
                                      aggregate.{{methodName}}({{methodArgs}});
                                      return Task.CompletedTask;
                                  }
                              }
                              """;

        ctx.AddSource($"{model.AggregateName}_{handlerName}.g.cs", handlerSource);
    }

    private static string GetCommandName(string aggregateName, string method, IMethodSymbol symbol)
    {
        //var aggregate = aggregateName.Replace("Aggregate", string.Empty);
        var lastChar = method[^1];
        if (char.IsDigit(lastChar))
        {
            //Debug.WriteLine($"***** {method[..^1]}Command{lastChar - '0'}");
            return $"{method[..^1]}Command{lastChar - '0'}";
        }

        if (method == "Delete" || method == "Create")
        {
            return $"{method}{aggregateName.Replace("Aggregate", string.Empty)}Command";
        }

        return $"{method}Command";
    }

    private static string GetNamespace(SyntaxNode node)
    {
        while (node != null)
        {
            switch (node)
            {
                case FileScopedNamespaceDeclarationSyntax fileScoped:
                    return fileScoped.Name.ToString();

                case NamespaceDeclarationSyntax blockScoped:
                    return blockScoped.Name.ToString();

                default:
                    node = node.Parent;
                    break;
            }
        }

        return "MyTelegram.Domain";
    }

    private static bool IsCandidateMethod(SyntaxNode node)
    {
        return node is MethodDeclarationSyntax m
               && m.Modifiers.Any(SyntaxKind.PublicKeyword)
               && m.Parent is ClassDeclarationSyntax cls
               && cls.Identifier.Text.EndsWith("Aggregate");
    }

    private static bool HasAttribute(ISymbol symbol, string attributeName)
    {
        foreach (var attr in symbol.GetAttributes())
        {
            var name = attr.AttributeClass?.Name;

            if (string.Equals(name, attributeName, StringComparison.OrdinalIgnoreCase) ||
                string.Equals(name, $"{attributeName}Attribute", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static string? TryExtractEventName(MethodDeclarationSyntax methodSyntax)
    {
        var bodyText = methodSyntax.Body?.ToString()
                       ?? methodSyntax.ExpressionBody?.Expression?.ToString()
                       ?? string.Empty;

        const string pattern = "Emit(new ";
        var index = bodyText.IndexOf(pattern, StringComparison.Ordinal);
        if (index < 0)
        {
            return null;
        }

        index += pattern.Length;

        var span = bodyText.AsSpan(index);

        var length = 0;
        while (length < span.Length)
        {
            var c = span[length];
            if (char.IsLetterOrDigit(c) || c == '_')
            {
                length++;
                continue;
            }

            break;
        }

        if (length == 0)
        {
            return null;
        }

        return span[..length].ToString();
    }

    private static MethodInfoModel? TransformMethod(GeneratorSyntaxContext ctx)
    {
        var methodSyntax = (MethodDeclarationSyntax)ctx.Node;
        var methodSymbol = ctx.SemanticModel.GetDeclaredSymbol(methodSyntax);
        if (methodSymbol == null)
        {
            return null;
        }

        var classSymbol = methodSymbol.ContainingType;
        var isAutoGenEnabledAtClassLevel = false;
        var isAutoGenDisabledAtClassLevel = false;
        var isAutoGenEnabledAtMethod = HasAttribute(methodSymbol, "EnableAutoGenerationAttribute");
        var isAutoGenDisabledAtMethod = HasAttribute(methodSymbol, "DisableAutoGenerationAttribute");
        var doNotInheritRequestCommand = HasAttribute(methodSymbol, "DoNotInheritRequestCommandAttribute");

        if (classSymbol != null)
        {
            isAutoGenEnabledAtClassLevel = HasAttribute(classSymbol, "EnableAutoGenerationAttribute");
            //isAutoGenDisabledAtClassLevel = HasAttribute(classSymbol, "DisableAutoGenerationAttribute");
        }

        if (isAutoGenDisabledAtMethod)
        {
            return null;
        }

        if (!isAutoGenEnabledAtClassLevel && !isAutoGenEnabledAtMethod)
        {
            return null;
        }

        var bodyText = methodSyntax.Body?.ToString()
                       ?? methodSyntax.ExpressionBody?.Expression?.ToString()
                       ?? string.Empty;
        if (!bodyText.Contains("Emit(new"))
        {
            return null;
        }

        var cls = (ClassDeclarationSyntax)methodSyntax.Parent!;
        var ns = GetNamespace(cls);
        var aggregateName = cls.Identifier.Text;
        var idType = aggregateName.Replace("Aggregate", string.Empty) + "Id";

        var extractedEventName = TryExtractEventName(methodSyntax);
        if (extractedEventName == null)
        {
            Debug.WriteLine(
                $"Cannot extract event name from method {methodSyntax.Identifier.Text} in aggregate {aggregateName}");
        }

        var eventParameters = GetEventParameters(methodSyntax, ctx.SemanticModel);
        var commandParameters = new List<ParameterModel>();
        foreach (var item in methodSyntax.ParameterList.Parameters)
        {
            commandParameters.Add(new ParameterModel(
                ctx.SemanticModel.GetTypeInfo(item.Type!).Type!.ToDisplayString(
                    SymbolDisplayFormat.FullyQualifiedFormat),
                item.Identifier.Text, item.Default?.Value.ToString()));

            if (item.Default != null)
            {
                Debug.WriteLine($" {item.Identifier.Text} Default value:{item.Default.Value}");
            }
        }

        return new MethodInfoModel(
            ns,
            aggregateName,
            idType,
            extractedEventName,
            eventParameters,
            commandParameters,
            methodSyntax,
            methodSymbol,
            doNotInheritRequestCommand
        );
    }

    private static List<ParameterModel> GetEventParameters(MethodDeclarationSyntax methodSyntax,
        SemanticModel semanticModel)
    {
        var result = new List<ParameterModel>();
        var names = new HashSet<string>();

        var emitInvocations = methodSyntax.DescendantNodes()
            .OfType<InvocationExpressionSyntax>()
            .Where(IsEmitInvocation);

        var autoIndex = 0;

        foreach (var emitCall in emitInvocations)
        {
            if (emitCall.ArgumentList.Arguments.Count == 0)
            {
                continue;
            }

            if (emitCall.ArgumentList.Arguments.First().Expression
                is not ObjectCreationExpressionSyntax newExpr)
            {
                continue;
            }

            foreach (var arg in newExpr.ArgumentList?.Arguments ?? [])
            {
                string parameterName;
                ITypeSymbol typeSymbol;

                switch (arg.Expression)
                {
                    case IdentifierNameSyntax id:
                        parameterName = id.Identifier.Text;
                        typeSymbol = semanticModel.GetTypeInfo(id).Type!;
                        break;

                    case MemberAccessExpressionSyntax mem:
                        parameterName = mem.Name.Identifier.Text;
                        typeSymbol = semanticModel.GetTypeInfo(mem).Type!;
                        break;

                    default:

                        var extracted = ExtractParamName(arg.Expression);
                        parameterName = !string.IsNullOrEmpty(extracted) ? extracted : $"param{autoIndex++}";

                        typeSymbol = semanticModel.GetTypeInfo(arg.Expression).Type
                                     ?? semanticModel.Compilation.GetTypeByMetadataName("System.Object")!;

                        if (string.IsNullOrEmpty(extracted))
                        {
                            var filePath = methodSyntax.SyntaxTree.FilePath;
                            Debug.WriteLine($"### {filePath} {methodSyntax} {arg.Expression.ToFullString()}");
                        }

                        break;
                }

                parameterName = char.ToLowerInvariant(parameterName[0]) + parameterName[1..];
                if (names.Contains(parameterName))
                {
                    continue;
                }

                result.Add(new ParameterModel(typeSymbol.ToDisplayString(), parameterName));
                names.Add(parameterName);
            }
        }

        return result;
    }

    private static string ExtractParamName(ExpressionSyntax expr)
    {
        // 1. a ?? b
        if (expr is BinaryExpressionSyntax binary)
        {
            if (binary.IsKind(SyntaxKind.CoalesceExpression))
            {
                return ExtractParamName(binary.Left);
            }
        }

        // 2. a
        if (expr is IdentifierNameSyntax ident)
        {
            return ident.Identifier.Text;
        }

        // 3. a.b 
        if (expr is MemberAccessExpressionSyntax member)
        {
            return member.Name.Identifier.Text;
        }

        // 4. a?.b
        if (expr is ConditionalAccessExpressionSyntax { Expression: IdentifierNameSyntax cid })
        {
            return cid.Identifier.Text;
        }

        // 5.
        return null!;
    }

    private static bool IsEmitInvocation(InvocationExpressionSyntax inv)
    {
        if (inv.Expression is IdentifierNameSyntax id)
        {
            return id.Identifier.Text == "Emit";
        }

        if (inv.Expression is MemberAccessExpressionSyntax member)
        {
            return member.Name.Identifier.Text == "Emit";
        }

        return false;
    }

    private class ParameterModel(string parameterType, string parameterName, string? defaultValue = null)
    {
        public string ParameterType { get; } = parameterType;
        public string ParameterName { get; } = parameterName;
        public string? DefaultValue { get; } = defaultValue;
    }

    private sealed class MethodInfoModel(
        string ns,
        string aggregateName,
        string idType,
        string eventName,
        List<ParameterModel> eventParameters,
        List<ParameterModel> commandParameters,
        MethodDeclarationSyntax syntax,
        IMethodSymbol symbol,
        bool doNotInheritRequestCommand
        )
    {
        public string AggregateName { get; } = aggregateName;
        public string EventName { get; } = eventName;
        public string IdType { get; } = idType;
        public IMethodSymbol MethodSymbol { get; } = symbol;
        public bool DoNotInheritRequestCommand { get; } = doNotInheritRequestCommand;
        public MethodDeclarationSyntax MethodSyntax { get; } = syntax;
        public string Namespace { get; } = ns;
        public List<ParameterModel> EventParameters { get; } = eventParameters;
        public List<ParameterModel> CommandParameters { get; } = commandParameters;
    }
}